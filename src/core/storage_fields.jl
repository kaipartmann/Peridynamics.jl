# type parameters of the generated storage
# --------------------------------------------------------------------------------------

#=
The generated storage struct is parametric in the array type of every field, so that a whole
storage can be moved to another array backend with `Adapt.adapt`, and generic in one float
type `FT`, so that a simulation with a different float type is another instantiation of the
same struct instead of another struct.

One parameter is derived per distinct pair of element type and number of dimensions, in the
order in which the pairs first appear in the declarations, plus a leading `FT` if any field
follows the float type of the simulation. A field that is declared neither with a field
shape nor with an `Array` type, e.g. with an `MArray`, keeps the type it is declared with
and contributes no parameter.
=#

const FLOAT_TYPE_PARAM = :FT

"""
    StorageTypeParam

$(internal_api_warning())

One derived type parameter of a storage generated by [`@storage`](@ref): its `name`, the
element type of the fields it stands for, which is [`SimFloat`](@ref) if they follow the
float type of the simulation, and the number of dimensions `n_dims` of their arrays.
"""
struct StorageTypeParam
    name::Symbol
    eltype::Any
    n_dims::Int
end

"""
    derive_storage_type_params(decls)

$(internal_api_warning())

Derive the type parameters of a storage from its field declarations. Returns the derived
[`StorageTypeParam`](@ref)s in the order they appear in the struct header, a `Dict` that
maps the name of a field to the name of its type parameter, whether any field follows the
float type of the simulation and the header therefore starts with `FT`, and the names of the
fields declared with [`ConstitutiveState`](@ref) and [`DamageState`](@ref), which contribute
the trailing parameters `CMS` and `DMS` in that order.
"""
function derive_storage_type_params(decls)
    params = Vector{StorageTypeParam}()
    field_params = Dict{Symbol,Symbol}()
    uses_sim_float = false
    cm_state_field = nothing
    dmg_state_field = nothing
    for decl in decls
        if is_cm_state_decl(decl)
            isnothing(cm_state_field) || throw(ArgumentError(nested_state_twice_msg(:cm,
                                                                                    cm_state_field,
                                                                                    decl.name)))
            is_halo_decl(decl) && throw(ArgumentError(nested_state_halo_msg(:cm, decl)))
            cm_state_field = decl.name
            field_params[decl.name] = CM_STATE_TYPE_PARAM
            continue
        end
        if is_dmg_state_decl(decl)
            isnothing(dmg_state_field) || throw(ArgumentError(nested_state_twice_msg(:dmg,
                                                                                     dmg_state_field,
                                                                                     decl.name)))
            is_halo_decl(decl) && throw(ArgumentError(nested_state_halo_msg(:dmg, decl)))
            dmg_state_field = decl.name
            field_params[decl.name] = DMG_STATE_TYPE_PARAM
            continue
        end
        key = storage_field_param_key(decl)
        isnothing(key) && continue
        T, n_dims = key
        T === SimFloat && (uses_sim_float = true)
        idx = findfirst(p -> p.eltype === T && p.n_dims == n_dims, params)
        if isnothing(idx)
            push!(params, StorageTypeParam(storage_param_name(params, T, n_dims), T, n_dims))
            idx = lastindex(params)
        end
        field_params[decl.name] = params[idx].name
    end
    return (; params, field_params, uses_sim_float, cm_state_field, dmg_state_field)
end

# `kind` is `:cm` for the constitutive model and `:dmg` for the damage model; the two nested
# states are declared, checked and reported the same way
@inline nested_state_model(kind::Symbol) = kind === :cm ? "constitutive model" : "damage model"
@inline nested_state_marker(kind::Symbol) = kind === :cm ? "ConstitutiveState" : "DamageState"

function nested_state_twice_msg(kind::Symbol, first_field::Symbol, second_field::Symbol)
    msg = "a storage can carry the state of only one $(nested_state_model(kind)), but both "
    msg *= "`$(first_field)` and `$(second_field)` are declared with "
    msg *= "`$(nested_state_marker(kind))`!\n"
    return msg
end

function nested_state_halo_msg(kind::Symbol, decl::StorageFieldDecl)
    msg = "the storage field `$(decl.name)` holds the state of the "
    msg *= "$(nested_state_model(kind)) and cannot be annotated with "
    msg *= "`@$(decl.annotation)`!\n"
    msg *= "  The halo exchange does not descend into a nested field, so the state of a "
    msg *= "$(nested_state_model(kind)) is chunk-local. Bond state and point-local state "
    msg *= "need no exchange.\n"
    return msg
end

# The element type and the number of dimensions a field contributes, or `nothing` for a
# field whose type is not an `Array`, because only an array can be exchanged for the array
# of another backend.
function storage_field_param_key(decl::StorageFieldDecl)
    isnothing(decl.shape) || return (field_eltype(decl.shape), field_n_dims(decl.shape))
    T = decl.type
    (isa(T, Base.Type) && T <: Base.Array && isconcretetype(T)) || return nothing
    return (eltype(T), ndims(T))
end

function storage_param_name(params, ::Base.Type{T}, n_dims::Int) where {T}
    name = Symbol(storage_param_prefix(n_dims), "_", storage_param_suffix(T))
    any(p -> p.name === name, params) || return name
    n = 2
    while any(p -> p.name === Symbol(name, "_", n), params)
        n += 1
    end
    return Symbol(name, "_", n)
end

storage_param_prefix(n_dims::Int) = n_dims == 1 ? "V" : n_dims == 2 ? "M" : "A$(n_dims)"

storage_param_suffix(::Base.Type{SimFloat}) = string(FLOAT_TYPE_PARAM)
storage_param_suffix(::Base.Type{Float64}) = "F64"
storage_param_suffix(::Base.Type{Float32}) = "F32"
storage_param_suffix(::Base.Type{Float16}) = "F16"
storage_param_suffix(::Base.Type{Int64}) = "Int"
storage_param_suffix(::Base.Type{T}) where {T} = isa(T, DataType) ? string(nameof(T)) : "E"

"""
    storage_param_bound(param)

$(internal_api_warning())

Return the type expression a derived type parameter is bounded by in the generated storage
struct, e.g. `AbstractMatrix{FT}` for `M_FT`. The bound is abstract, so that a storage can
hold the arrays of any backend.
"""
function storage_param_bound(param::StorageTypeParam)
    E = storage_param_eltype(param)
    param.n_dims == 1 && return Expr(:curly, Base.AbstractVector, E)
    param.n_dims == 2 && return Expr(:curly, Base.AbstractMatrix, E)
    return Expr(:curly, Base.AbstractArray, E, param.n_dims)
end

"""
    storage_param_default(param)

$(internal_api_warning())

Return the type expression of the array a derived type parameter stands for in a simulation
on the CPU, e.g. `Matrix{FT}` for `M_FT`. This is what [`storage_type`](@ref) instantiates
the storage with.
"""
function storage_param_default(param::StorageTypeParam)
    E = storage_param_eltype(param)
    param.n_dims == 1 && return Expr(:curly, Base.Vector, E)
    param.n_dims == 2 && return Expr(:curly, Base.Matrix, E)
    return Expr(:curly, Base.Array, E, param.n_dims)
end

@inline function storage_param_eltype(param::StorageTypeParam)
    return param.eltype === SimFloat ? FLOAT_TYPE_PARAM : param.eltype
end

"""
    storage_field_decl_type(decl, field_params)

$(internal_api_warning())

Return the type of a field in the generated storage struct, which is the name of its derived
type parameter, or the type it is declared with if it has none.
"""
@inline function storage_field_decl_type(decl::StorageFieldDecl, field_params)
    return get(field_params, decl.name, decl.type)
end
