"""
    force_density_point!(storage, system, mat, paramsetup, t, Δt, i)

$(extension_api_note())

Calculate the internal force density of point `i` and accumulate it into
`storage.b_int`. This is the one method a material has to define, everything else about a
material is declared with [`@params`](@ref) and [`@storage`](@ref).

It is called once per local point and per time step, from inside a loop over
[`each_point_idx`](@ref) that runs on every thread and on every MPI rank. A method must
therefore only ever write to the columns of point `i` and read every other point through
the system, which is what makes the same material run under multithreading and MPI without
a change.

# Arguments

- `storage`: The storage of the body chunk, holding every field of the simulation.
- `system`: The system of the body chunk, e.g. a [`BondSystem`](@ref). Dispatch on it to say
    which discretization the material is written for.
- `mat`: The material.
- `paramsetup`: The parameter setup of the body chunk, one set of point parameters or a
    handler for a body where [`material!`](@ref) was called more than once.
    `get_params(paramsetup, i)` resolves the set of point `i` once at the top, and a material
    that averages a parameter across a bond reads the set of the neighbor with
    `get_params(paramsetup, j)` inside the loop, see [`get_params`](@ref).
- `t::Real`: The current simulation time.
- `Δt::Real`: The current time step.
- `i::Int`: The index of the local point that is evaluated.

# Default

A `MethodError`, because there is nothing sensible a material could inherit here.

# Example

The force density of a bond-based material. The bonds that failed were deactivated by
[`calc_failure!`](@ref) right before, so a material only multiplies
[`bond_is_active`](@ref) in. The current length of the bond comes from
[`current_bond_length`](@ref) and never from gathering the two positions and taking the
norm.

```julia
function Peridynamics.force_density_point!(storage, system::Peridynamics.BondSystem,
                                           mat::MyMaterial, paramsetup, t, Δt, i)
    (; volume) = system
    params = Peridynamics.get_params(paramsetup, i)
    for bond_id in Peridynamics.each_bond_idx(system, i)
        j = Peridynamics.get_neighbor(system, bond_id)
        L = Peridynamics.reference_bond_length(system, bond_id)
        Δxij = Peridynamics.get_vector_diff(storage.position, i, j,
                                            Peridynamics.dims(system))
        l = Peridynamics.current_bond_length(storage, system, i, bond_id)
        ε = (l - L) / L
        ω = Peridynamics.bond_is_active(storage, system, bond_id) *
            Peridynamics.surface_correction_factor(system, bond_id)
        b = ω * params.bc * ε * volume[j] / l .* Δxij
        Peridynamics.update_add_vector!(storage.b_int, i, b, Peridynamics.dims(system))
    end
    return nothing
end
```

A kernel that needs the stretch and not the length takes [`bond_stretch`](@ref) instead.

See also [`storage_type`](@ref), [`get_params`](@ref), [`each_bond_idx`](@ref),
[`current_bond_length`](@ref), [`bond_stretch`](@ref), [`@storage`](@ref).
"""
function force_density_point! end

"""
    storage_type(mat)
    storage_type(mat, ::Type{FT})
    storage_type(mat, ::Type{FT}, ::Val{N})

$(extension_api_note())

Return the storage type of a material, instantiated for the float type `FT` and the number
of spatial dimensions `N` of the simulation. The returned instantiation holds the arrays of
the CPU. `N` is the leading type parameter of the generated storage and is what
[`get_n_dim`](@ref) reads off it. It defaults to `3`, and the storage of a body chunk gets
it from the system of the chunk, so a storage can never disagree with its system.

# Default

An [`InterfaceError`](@ref) that asks for a [`@storage`](@ref) declaration, which generates
this method.

See also [`@storage`](@ref), [`init_field`](@ref), [`get_n_dim`](@ref).
"""
function storage_type(mat::AbstractMaterial)
    return throw(InterfaceError(mat, "storage_type", storage_macro_hint(mat)))
end

function storage_macro_hint(mat)
    name = mat isa Type ? nameof(mat) : nameof(typeof(mat))
    msg = "Declare the storage of `$(name)` with `@storage`, e.g.\n"
    msg *= "        Peridynamics.@storage $(name) struct MyStorage\n"
    msg *= "            @inherit VelocityVerletFields\n"
    msg *= "            my_field::PointScalar\n"
    msg *= "            dmg_state::DamageState\n"
    msg *= "        end\n"
    msg *= "    which defines `storage_type` and `get_storage` for you."
    return msg
end

# a storage that is not generic in its float type or its dimension, i.e. one that is not
# generated by `@storage`, ignores both
storage_type(mat::AbstractMaterial, ::Type) = storage_type(mat)
storage_type(mat::AbstractMaterial, ::Type, ::Val) = storage_type(mat)

function get_storage(material, solver, system)
    return throw(InterfaceError(material, "get_storage", storage_macro_hint(material)))
end

"""
    init_field(material, solver, system, ::Val{field})

$(extension_api_note())

Return the initial value of a storage field. Every field of a storage generated by
[`@storage`](@ref) is allocated by this function, in this order:

1. the system, which owns `position` and every field whose initial value is system
   knowledge, e.g. the neighbor count that `n_active_bonds` starts with,
2. the field shape of a field declared with [`@lth`](@ref) or [`@htl`](@ref), because
   whether a field has halo entries is storage knowledge that a time solver cannot have,
3. the time solver, which says whether it needs the field and at which extent,
4. the field shape of every other declared field,
5. an `InterfaceError` that asks for an `init_field` method.

A method of this function for a specific material is more specific than the fallback above
and therefore wins, which is the escape hatch for a field that no field shape describes and
for a shaped field that has to be filled by hand.

# Default

The five steps above, ending in an [`InterfaceError`](@ref) when no step answers.

# Example

```julia
function Peridynamics.init_field(::MyMaterial, ::Peridynamics.AbstractTimeSolver,
                                 system::Peridynamics.AbstractSystem, ::Val{:my_field})
    return zeros(Peridynamics.get_n_points(system))
end
```

See also [`@storage`](@ref), [`storage_type`](@ref).
"""
function init_field(material, solver, system, field)
    Storage = storage_type(material, float_type(system), dims(system))
    field_value_system = init_field_system(system, field)
    isnothing(field_value_system) || return field_value_system
    field_value_halo = init_field_storage(Storage, system, field, HaloPoints())
    isnothing(field_value_halo) || return field_value_halo
    field_value_solver = resolve_solver_field(init_field_solver(solver, system, field),
                                              Storage, system, field)
    isnothing(field_value_solver) || return field_value_solver
    field_value_storage = init_field_storage(Storage, system, field, LocalPoints())
    isnothing(field_value_storage) || return field_value_storage
    method_msg = "init_field(::$(typeof(material)), "
    method_msg *= "::$(typeof(solver)), "
    method_msg *= "::$(typeof(system)), "
    method_msg *= "::$(typeof(field)))"
    return throw(InterfaceError(material, method_msg, init_field_hint(field)))
end

#=
A time solver answers `init_field_solver` either with one of the markers of
`core/storage_fields.jl`, which is how every solver of this package does it, or with the
field itself, which is how a third party solver allocates a field that no field shape
describes. Anything that is not a marker is passed through unchanged, including the
`nothing` of a solver that has nothing to say about the field.
=#
@inline resolve_solver_field(field_value, Storage, system, field) = field_value

@inline function resolve_solver_field(::EmptyField, Storage, system, field)
    return alloc_empty_field(Storage, field)
end

@inline function resolve_solver_field(marker::FullField, Storage, system, field)
    field_value = init_field_storage(Storage, system, field, marker)
    isnothing(field_value) && throw(ArgumentError(unshaped_field_msg(Storage, field)))
    return field_value
end

function unshaped_field_msg(::Type{S}, ::Val{Field}) where {S,Field}
    msg = "the time solver needs the storage field `$(Field)`, but `$(nameof(S))` declares "
    msg *= "it with a container type!\n"
    msg *= "  Only a field declared with a field shape can be sized by a time solver. "
    msg *= "Declare it with the shape it has, e.g.\n"
    msg *= "        $(Field)::PointVector\n"
    msg *= "    or inherit it from the field block of the time solver, e.g.\n"
    msg *= "        @inherit VelocityVerletFields\n"
    msg *= "    or define an `init_field` method that allocates it.\n"
    return msg
end

"""
    init_field_storage(::Type{Storage}, system, field, extent)

$(internal_api_warning())

Return the value of `field` as it follows from the field shape it was declared with in the
[`@storage`](@ref) definition of `Storage`, or `nothing` if the field was declared with a
plain container type or does not have the requested `extent`. Methods of this function are
generated by `@storage`, so a field declared with a field shape never needs an
[`init_field`](@ref) method.
"""
@inline function init_field_storage(::Type, system, field, extent)
    return nothing
end

function init_field_hint(::Val{Field}) where {Field}
    msg = "Either declare `$(Field)` with a field shape in the `@storage` definition, "
    msg *= "e.g.\n"
    msg *= "        $(Field)::PointScalar\n"
    msg *= "    or inherit it from the storage of the material family, e.g.\n"
    msg *= "        @inherit RKCStorage\n"
    msg *= "    or define the `init_field` method shown above."
    return msg
end

