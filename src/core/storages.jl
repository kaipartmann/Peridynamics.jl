#=
Reading a storage flat, the twin of the parameter forwarding in `core/param_fields.jl`:
`getproperty` forwards a name that is not a field into the nested states, so a kernel reads
`storage.bond_active` without knowing that the damage model carries the field. The
`@generated` function computes the exact `getfield` chain per (type, name), so a property
literal compiles to a direct load and the forwarding costs nothing, which is asserted by
the "storage property forwarding" item of `test/perf/perf.jl`. Everything generated by the
macros reads fields with `getfield`, so the forwarding cannot recurse.
=#
Base.@constprop :aggressive @inline function Base.getproperty(storage::AbstractStorage,
                                                              name::Symbol)
    return get_storage_property(storage, Val(name))
end

# `storage.field .= value` reaches the field through `dotgetproperty`, one call deeper than
# a plain read, and the property literal has to survive into the `Val` there as well
Base.@constprop :aggressive @inline function Base.dotgetproperty(storage::AbstractStorage,
                                                                 name::Symbol)
    return get_storage_property(storage, Val(name))
end

@generated function get_storage_property(storage::S,
                                         ::Val{F}) where {S<:AbstractStorage,F}
    F in fieldnames(S) && return :(Base.getfield(storage, $(QuoteNode(F))))
    exprs, owners = Any[], Symbol[]
    for field in fieldnames(S)
        FT = fieldtype(S, field)
        FT <: Union{AbstractConstitutiveState,AbstractDamageState} || continue
        F in fieldnames(FT) || continue
        push!(owners, field)
        push!(exprs, :(Base.getfield(Base.getfield(storage, $(QuoteNode(field))),
                                     $(QuoteNode(F)))))
    end
    length(owners) == 1 && return exprs[1]
    # not found anywhere: `getfield` throws the native no-field error of this Julia version
    isempty(owners) && return :(Base.getfield(storage, $(QuoteNode(F))))
    return :(Peridynamics.ambiguous_storage_property($(QuoteNode(F)), storage,
                                                     $(Tuple(owners))))
end

function ambiguous_storage_property(name::Symbol, @nospecialize(storage), owners)
    msg = "the field `$(name)` exists in $(join(("`$(o)`" for o in owners), " and "))"
    msg *= " of `$(nameof(typeof(storage)))`!\n"
    msg *= "  Read it from the model state directly, e.g. "
    msg *= "`storage.$(first(owners)).$(name)`.\n"
    return throw(ArgumentError(msg))
end

function Base.propertynames(storage::AbstractStorage, private::Bool=false)
    return storage_property_names(storage)
end

# the fields plus everything the nested states hold, which is what `getproperty` accepts
@generated function storage_property_names(storage::S) where {S<:AbstractStorage}
    names = Symbol[]
    for field in fieldnames(S)
        push!(names, field)
        FT = fieldtype(S, field)
        FT <: Union{AbstractConstitutiveState,AbstractDamageState} || continue
        append!(names, fieldnames(FT))
    end
    return Tuple(names)
end
