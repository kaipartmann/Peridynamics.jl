function get_storage_structdef(storage_expr, mod::Module,
                               default_supertype=:(Peridynamics.AbstractStorage))
    storage_type, supertype = get_storage_header(storage_expr, default_supertype)
    decls = get_field_decls(storage_expr.args[3].args, mod)
    (; params, field_params, uses_sim_float, cm_state_field,
       dmg_state_field) = derive_storage_type_params(decls)
    fields_exprs = [Expr(:(::), d.name, storage_field_decl_type(d, field_params))
                    for d in decls]
    fields_block = Expr(:block, fields_exprs...)
    header = storage_header_expr(storage_type, supertype, params, uses_sim_float,
                                 cm_state_field, dmg_state_field)
    storage_struct = Expr(:struct, storage_expr.args[1], header, fields_block)
    return (; storage_struct, storage_type, decls, params, field_params, uses_sim_float,
            cm_state_field, dmg_state_field)
end

"""
    storage_header_expr(storage_type, supertype, params, uses_sim_float)

$(internal_api_warning())

Assemble the header of the generated storage struct from the derived type parameters, see
[`derive_storage_type_params`](@ref). A storage without a derived parameter, i.e. one whose
fields are all declared with a type that is not an `Array`, keeps a plain header.
"""
function storage_header_expr(storage_type, supertype, params, uses_sim_float,
                             cm_state_field=nothing, dmg_state_field=nothing)
    param_exprs = Any[DIM_TYPE_PARAM]
    uses_sim_float && push!(param_exprs, Expr(:(<:), FLOAT_TYPE_PARAM, Real))
    for param in params
        push!(param_exprs, Expr(:(<:), param.name, storage_param_bound(param)))
    end
    # a nested state is whatever the model declares, so its parameter is unbounded;
    # `Nothing` for a model without state. `CMS` comes before `DMS`.
    isnothing(cm_state_field) || push!(param_exprs, CM_STATE_TYPE_PARAM)
    isnothing(dmg_state_field) || push!(param_exprs, DMG_STATE_TYPE_PARAM)
    return Expr(:(<:), Expr(:curly, storage_type, param_exprs...), supertype)
end

"""
    storage_dim_constructor_expr(storage_type, decls, params, uses_sim_float, field_params)

$(internal_api_warning())

Assemble the outer constructor that fixes the number of spatial dimensions of a generated
storage or model state. `N` is the one type parameter that no field answers, so the default
constructor cannot infer it: a storage takes it from the system it is built for. This
constructor names it and lets the field types answer every other parameter, which is what
the storage constructor and `Adapt.adapt_structure` call.
"""
function storage_dim_constructor_expr(storage_type, decls, params, uses_sim_float,
                                      field_params, cm_state_field=nothing,
                                      dmg_state_field=nothing)
    where_params = Any[DIM_TYPE_PARAM]
    uses_sim_float && push!(where_params, Expr(:(<:), FLOAT_TYPE_PARAM, Real))
    curly_params = Any[DIM_TYPE_PARAM]
    uses_sim_float && push!(curly_params, FLOAT_TYPE_PARAM)
    for param in params
        push!(where_params, Expr(:(<:), param.name, storage_param_bound(param)))
        push!(curly_params, param.name)
    end
    if !isnothing(cm_state_field)
        push!(where_params, CM_STATE_TYPE_PARAM)
        push!(curly_params, CM_STATE_TYPE_PARAM)
    end
    if !isnothing(dmg_state_field)
        push!(where_params, DMG_STATE_TYPE_PARAM)
        push!(curly_params, DMG_STATE_TYPE_PARAM)
    end
    # a storage whose only parameter is `N` needs no method of its own: `S{N}(fields...)` is
    # then the default constructor, and generating it again would only recurse
    length(curly_params) == 1 && return Expr(:block)
    args = [Expr(:(::), d.name, storage_field_decl_type(d, field_params)) for d in decls]
    names = [d.name for d in decls]
    call = Expr(:call, Expr(:curly, esc(storage_type), DIM_TYPE_PARAM), args...)
    signature = Expr(:where, call, where_params...)
    body = Expr(:return,
                Expr(:call, Expr(:curly, esc(storage_type), curly_params...), names...))
    return Expr(:function, signature, Expr(:block, body))
end

"""
    get_n_dim_expr(storage_type)

$(internal_api_warning())

Assemble the [`get_n_dim`](@ref) method of a generated storage or model state, which reads
the leading type parameter of the struct.
"""
function get_n_dim_expr(storage_type)
    return quote
        @inline function Peridynamics.get_n_dim(::$(esc(storage_type)){$(DIM_TYPE_PARAM)}) where {$(DIM_TYPE_PARAM)}
            return $(DIM_TYPE_PARAM)
        end
    end
end

"""
    get_storage_header(storage_expr)

$(internal_api_warning())

Return the name and the supertype of the storage struct of a [`@storage`](@ref) definition.
A definition that declares its own type parameters is rejected, because `@storage` derives
them from the field declarations.
"""
function get_storage_header(storage_expr, default_supertype=:(Peridynamics.AbstractStorage))
    header = storage_expr.args[2]
    if header isa Symbol
        # case `struct MyStorage`
        return header, default_supertype
    elseif header isa Expr && header.head === :(<:) && header.args[1] isa Symbol
        # case `struct MyStorage <: AbstractStorage`
        return header.args[1], header.args[2]
    end
    return throw(ArgumentError(storage_header_msg(header)))
end

function storage_header_msg(header)
    is_parametric = header isa Expr &&
                    (header.head === :curly ||
                     (header.head === :(<:) && header.args[1] isa Expr &&
                      header.args[1].head === :curly))
    is_parametric || return "storage header `$(header)` not supported!\n"
    msg = "a storage cannot declare its own type parameters, got `$(header)`!\n"
    msg *= "  `@storage` derives the type parameters of a storage from its field "
    msg *= "declarations, so that the storage is generic in the float type of the "
    msg *= "simulation and can be moved to another array backend. Declare the storage "
    msg *= "without type parameters and pin the element type of a field in its field shape "
    msg *= "instead, e.g.\n"
    msg *= "        position::PointVector{Float64}\n"
    return msg
end

