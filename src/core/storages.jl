    return throw(ArgumentError("$storage is not a valid storage type!\n"))
end

function typecheck_storage_fields(::Type{S}, fields::NTuple{N,Symbol}) where {S,N}
    storage_fields = fieldnames(S)
    for field in fields
        if !in(field, storage_fields)
            msg = "storage $(S) has no field `$(field)`!\n"
            throw(ArgumentError(msg))
        end
    end
    return nothing
end

function typecheck_req_fields_missing(::Type{Storage}, req_fields) where {Storage}
    storage_fields = fieldnames(Storage)
    for req_field in req_fields
        if !in(req_field, storage_fields)
            error("required field $req_field not found in $(Storage)!\n")
        end
    end
    return false
end

"""
    required_fields(::Type{Material})

$(internal_api_warning())

Return all storage fields that can be determined from the material *type* alone. This is
the cheap check done by [`@storage`](@ref) at macro expansion time.

Everything that depends on the material *instance*, the damage model or the time solver
cannot be known here and is therefore checked at setup time with
[`check_storage_contract`](@ref).
"""
function required_fields(::Type{Material}) where {Material<:AbstractMaterial}
    return required_fields_fracture(Material)
end

"""
    req_storage_fields(mat)
    req_storage_fields(mat, dmgmodel)
    req_storage_fields(solver)

$(internal_api_warning())

Return the storage fields that are required by a material family, by a damage model in
combination with a material, or by a time solver. All methods return a `Tuple` of `Symbol`s
and default to an empty tuple, so only the parts of the contract that really exist have to
be declared.

These declarations are collected by [`check_storage_contract`](@ref) when a [`Job`](@ref)
is created.

# Example
```julia
Peridynamics.req_storage_fields(::MyMaterialFamily) = (:defgrad, :weighted_volume)
Peridynamics.req_storage_fields(::MyMaterialFamily, ::MyDamageModel) = (:bond_damage,)
```
"""
function req_storage_fields end

req_storage_fields(::AbstractMaterial) = ()

"""
    storage_contract(mat::AbstractMaterial, solver::AbstractTimeSolver)

$(internal_api_warning())

Return the complete storage contract of `mat` in combination with `solver` as a `Tuple` of
`(fields, reason)` pairs, where `reason` describes why the fields are required.
"""
function storage_contract(mat::AbstractMaterial, solver::AbstractTimeSolver)
    M, S = typeof(mat), typeof(solver)
    dmgmodel = get_dmgmodel(mat)
    return ((required_fields_fracture(M), "the system of `$(nameof(M))`"),
            (req_storage_fields(mat), "the material `$(nameof(M))`"),
            (req_storage_fields(mat, dmgmodel), "the damage model `$(_name_of(dmgmodel))`"),
            (req_storage_fields(solver), "the time solver `$(nameof(S))`"))
end

@inline _name_of(x) = nameof(typeof(x))
@inline _name_of(::Nothing) = :Nothing

"""
    check_storage_contract(spatial_setup, solver::AbstractTimeSolver)

$(internal_api_warning())

Check if the storage of every material of `spatial_setup` contains all fields that are
required by the material itself, by its damage model and by the time solver `solver`.
Throws a [`StorageContractError`](@ref) that names the missing fields and the reason why
they are required.

This check is done once when a [`Job`](@ref) is created. In contrast to the check inside
[`@storage`](@ref), the damage model and the time solver are known here, so the parts of
the contract that depend on them can finally be verified.
"""
function check_storage_contract(mat::AbstractMaterial, solver::AbstractTimeSolver)
    S = storage_type(mat)
    storage_fields = fieldnames(S)
    missing_fields = Vector{Pair{Symbol,String}}()
    for (fields, reason) in storage_contract(mat, solver)
        for field in fields
            in(field, storage_fields) && continue
            any(x -> first(x) === field, missing_fields) && continue
            push!(missing_fields, field => reason)
        end
    end
    isempty(missing_fields) && return nothing
    throw(StorageContractError(S, typeof(mat), typeof(solver), missing_fields))
end

function check_storage_contract(body::AbstractBody, solver::AbstractTimeSolver)
    return check_storage_contract(body.mat, solver)
end

function check_storage_contract(ms::AbstractMultibodySetup, solver::AbstractTimeSolver)
    for body in each_body(ms)
        check_storage_contract(body, solver)
    end
    return nothing
end

