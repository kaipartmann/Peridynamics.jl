    storage_type(mat, ::Type{FT})

$(extension_api_note())

Return the storage type of a material, instantiated for the float type `FT` of the
simulation. The storage generated by [`@storage`](@ref) is parametric in the array type of
every field, and this method returns the instantiation with the arrays of the CPU, so that
`body_chunk_type` and everything built from it stay concrete.
