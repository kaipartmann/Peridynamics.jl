"""
    @storage material storage
    @storage material solver storage

$(extension_api_note())

A macro for automatic creation of a storage type. The macro then maps a specified `material`
type with the `storage` structure. When no solver is specified, this storage is always used
independently of the solver type. Specifying a solver allows the usage of customized
storages for a solver.

# Declaring a field

A field is declared with a **field shape**, which says what the field *is*. The shape
determines the container type, the element type and the allocation, so a field declared with
a shape needs no [`init_field`](@ref) method:

| shape | container | rows | entries |
|:---|:---|:---|:---|
| [`PointScalar`](@ref) | `Vector` | – | points |
| [`PointVector`](@ref) | `Matrix` | `get_n_dim(system)` | points |
| [`PointTensor`](@ref) | `Matrix` | `get_n_dim(system)^2` | points |
| [`PointSymTensor`](@ref) | `Matrix` | `d * (d + 1) ÷ 2` | points |
| [`PointField{N}`](@ref PointField) | `Matrix` | `N` | points |
| [`BondScalar`](@ref) | `Vector` | – | bonds |
| [`BondVector`](@ref) | `Matrix` | `get_n_dim(system)` | bonds |
| [`BondTensor`](@ref) | `Matrix` | `get_n_dim(system)^2` | bonds |
| [`BondSymTensor`](@ref) | `Matrix` | `d * (d + 1) ÷ 2` | bonds |
| [`BondField{N}`](@ref BondField) | `Matrix` | `N` | bonds |
| [`DofVector`](@ref) | `Vector` | – | degrees of freedom |

A **point shape makes the field point data**, which is what can be exported to VTK files. A
bond or dof shape is not point data.

## Element type

A shape written without an element type follows the float type of the simulation, see
[`SimFloat`](@ref). A shape with an element type pins it for every simulation, which is why
`position` is declared `PointVector{Float64}`. `PointScalar{Bool}` and `PointScalar{Int}`
are the non-float cases.

## Annotations

Only the halo exchange is annotated, everything else follows from the shape. Both
annotations give the field one entry per local *and* halo point:

- `@lth`: local-to-halo exchange during the simulation, i.e. the halo entries are updated
    from the chunk that owns the points.
- `@htl`: halo-to-local exchange, i.e. the halo entries are added to the local entries of
    the owning chunk.
- `@inherit`: includes all fields of one or more other storages or of field blocks defined
    with [`@storage_fields`](@ref). See [`@inherit`](@ref) for the merge rules.

## Initial value

The initial value of a shaped field is written `= value`:

| written | result |
|:---|:---|
| omitted | zeros |
| a `Number`, e.g. `= 1.0` or `= true` | every entry that value |
| a `LinearAlgebra.UniformScaling`, e.g. `= I` or `= 2I` | every column that tensor |

A `UniformScaling` requires a shape whose rows are the entries of a square tensor, e.g.
`PointTensor`.

## Anything a shape does not describe

A field can also be declared with a plain container type, e.g.
`zem_stiffness::MArray{NTuple{4,3},Float64,4,81}`. Such a field is not point data and it
needs an [`init_field`](@ref) method that allocates it. A container type that is an `Array`,
e.g. `Vector{Float64}`, still takes part in the type parameters described below, everything
else keeps the type it is declared with.

A field that a time solver works with is the one case where a container type is not enough,
because a solver says only whether it needs the field and at which extent. Inheriting the
field block of the solver, e.g. `@inherit VelocityVerletFields`, declares all of them with
the right shape.

An `init_field` method is also the escape hatch for a *shaped* field: it is more specific
than the generic fallback and therefore wins, so a field can keep its shape, and with it
its type, its size and its export status, while being filled by hand:

````julia
function Peridynamics.init_field(::MyMaterial, ::Peridynamics.AbstractTimeSolver,
                                 system::Peridynamics.AbstractSystem, ::Val{:my_field})
    return ...
end
````

# The generated type

The generated struct must not declare type parameters of its own, because the macro derives
them from the declarations: a leading `N` for the number of spatial dimensions, then `FT`
for the float type of the simulation, then one parameter per distinct combination of element
type and number of array dimensions, and finally one unbounded parameter per nested state
(`cm_state`, `dmg_state`) that the storage declares. The storage of the bond-based material
below becomes

````julia
struct BBStorage{N,FT<:Real,M_F64<:AbstractMatrix{Float64},M_FT<:AbstractMatrix{FT},
                 V_FT<:AbstractVector{FT},DMS} <: AbstractStorage
    position::M_F64
    displacement::M_FT
    ...
    dmg_state::DMS
end
````

so `storage_type(mat)` returns the instantiation with the arrays of the CPU,
`storage_type(mat, Float32)` the one with `Float32` arrays,
`storage_type(mat, Float64, Val(2))` the two-dimensional one, and
`Adapt.adapt(backend, s)` moves a whole storage to another array backend. `N` is what [`get_n_dim`](@ref) reads off a storage, and with it
[`dims`](@ref) works on a storage exactly as it does on a system. Dispatch on the storage
therefore has to be written `::Type{<:BBStorage}` instead of `::Type{BBStorage}`, while
`::BBStorage` is unchanged.

# Example
Example definition of the storage for the bond-based material:
````julia
@storage BBMaterial struct BBStorage <: AbstractStorage
    @inherit VelocityVerletFields DynamicRelaxationFields NewtonKrylovFields
    @inherit BondLengthCache
    strain_energy_density::PointScalar
    dmg_state::DamageState
end
````

The fracture bookkeeping (`damage`, `n_active_bonds`, `bond_active`) is not declared here:
it lives in the state of the damage model, which the `dmg_state::DamageState` field
carries, see [`DamageState`](@ref) and [`@dmg_storage`](@ref). The storage still reads flat,
`storage.bond_active` reaches into the state.
"""
macro storage end

macro storage(material, storage)
    macrocheck_input_material(material)
    macrocheck_input_storage_struct(storage)
    return __storage(material, storage, __module__)
end

macro storage(material, solver, storage)
    macrocheck_input_material(material)
    macrocheck_input_timesolver(solver)
    macrocheck_input_storage_struct(storage)
    return __storage(material, storage, __module__, solver)
end

function __storage(material, storage, mod::Module, timesolver=AbstractTimeSolver)
    local _storage_struct_data = get_storage_structdef(storage, mod)
    local _storage_struct = _storage_struct_data.storage_struct
    local _storage_type = _storage_struct_data.storage_type
    local _decls = _storage_struct_data.decls
    local _params = _storage_struct_data.params
    local _field_params = _storage_struct_data.field_params
    local _uses_sim_float = _storage_struct_data.uses_sim_float
    local _cm_state_field = _storage_struct_data.cm_state_field
    local _dmg_state_field = _storage_struct_data.dmg_state_field

    local _point_field_names = Tuple(QuoteNode(d.name) for d in _decls if is_point_decl(d))
    local _htl_field_names = Tuple(QuoteNode(d.name)
                                   for d in _decls if d.annotation === :htl)
    local _lth_field_names = Tuple(QuoteNode(d.name)
                                   for d in _decls if d.annotation === :lth)
    local _halo_field_names = (_htl_field_names..., _lth_field_names...)

    # one literal `Val` per field instead of one built from a runtime `Symbol`, so that
    # every `init_field` call is resolved at compile time and the whole construction of a
    # storage is type stable
    local _init_field_calls = [
        if is_cm_state_decl(_decl)
            # the state of the constitutive model is not a field of the storage in the sense
            # of `init_field`: it is allocated by the model, not by the system or the solver
            :(Peridynamics.init_constitutive_state(mat, solver, system))
        elseif is_dmg_state_decl(_decl)
            # the same for the state of the damage model
            :(Peridynamics.init_damage_state(mat, solver, system))
        else
            :(Peridynamics.init_field(mat, solver, system,
                                      Base.Val($(QuoteNode(_decl.name)))))
        end
        for _decl in _decls
    ]

    local _dim_constructor = storage_dim_constructor_expr(_storage_type, _decls, _params,
                                                          _uses_sim_float, _field_params,
                                                          _cm_state_field, _dmg_state_field)

    local _get_n_dim = get_n_dim_expr(_storage_type)

    # the storage takes its dimension from the system it is built for, so the two can never
    # disagree
    local _constructor = quote
        function $(esc(_storage_type))(mat::$(esc(material)), solver::$(esc(timesolver)),
                                       system::Peridynamics.AbstractSystem)
            return $(esc(_storage_type)){Peridynamics.get_n_dim(system)}($(_init_field_calls...))
        end
    end

    local _storage_type_function = storage_type_function(material, _storage_type, _params,
                                                         _uses_sim_float, _cm_state_field,
                                                         _dmg_state_field)

    local _constitutive_state = if isnothing(_cm_state_field)
        Expr(:block)
    else
        quote
            @inline function Peridynamics.constitutive_state(s::$(esc(_storage_type)))
                return Base.getfield(s, $(QuoteNode(_cm_state_field)))
            end
            function Peridynamics.has_constitutive_state(::Base.Type{<:$(esc(_storage_type))})
                return true
            end
        end
    end

    local _damage_state = if isnothing(_dmg_state_field)
        Expr(:block)
    else
        quote
            @inline function Peridynamics.damage_state(s::$(esc(_storage_type)))
                return Base.getfield(s, $(QuoteNode(_dmg_state_field)))
            end
            function Peridynamics.has_damage_state(::Base.Type{<:$(esc(_storage_type))})
                return true
            end
        end
    end

    #=
    Moving a storage to another array backend is a matter of moving every field, because the
    struct is parametric in the array type of each of them and its outer constructor
    re-infers the parameters. A storage without a derived type parameter has nothing that
    could be moved, and rebuilding it would convert the adapted fields back, so it gets no
    method.
    =#
    local _adapt_args = [
        :(Adapt.adapt(to, Base.getfield(s, $(QuoteNode(_decl.name))))) for _decl in _decls
    ]
    local _adapt_structure = if isempty(_params)
        Expr(:block)
    else
        quote
            function Adapt.adapt_structure(to, s::$(esc(_storage_type)){N}) where {N}
                return $(esc(_storage_type)){N}($(_adapt_args...))
            end
        end
    end

    local _get_storage = quote
        function Peridynamics.get_storage(mat::$(esc(material)), solver::$(esc(timesolver)),
                                          system::Peridynamics.AbstractSystem)
            return $(esc(_storage_type))(mat, solver, system)
        end
    end

    local _point_data_fields = [
        quote
            function Peridynamics.point_data_field(s::$(esc(_storage_type)),
                                                   ::Val{$(_field)})
                return Base.getfield(s, $(_field))
            end
        end
        for _field in _point_field_names
    ]

    # a storage that carries a damage state also serves the point data the state declares,
    # e.g. the `damage` of the fracture bookkeeping, so the flat tuple is composed with the
    # point data of the concrete state type and unknown `Val`s are forwarded into the state
    local _get_all_point_data_fields = if isnothing(_dmg_state_field)
        quote
            function Peridynamics.point_data_fields(::Base.Type{<:$(esc(_storage_type))})
                return $(Expr(:tuple, _point_field_names...))
            end
        end
    else
        quote
            function Peridynamics.point_data_fields(::Base.Type{S}) where {S<:$(esc(_storage_type))}
                return ($(Expr(:tuple, _point_field_names...))...,
                        Peridynamics.nested_point_data_fields(Base.fieldtype(S, $(QuoteNode(_dmg_state_field))))...)
            end
            function Peridynamics.point_data_field(s::$(esc(_storage_type)), v::Base.Val)
                return Peridynamics.point_data_field(Peridynamics.damage_state(s), v)
            end
        end
    end

    local _halo_to_loc_fields = quote
        function Peridynamics.halo_to_loc_fields(::$(esc(_storage_type)))
            return $(Expr(:tuple, _htl_field_names...))
        end
    end

    local _loc_to_halo_fields = quote
        function Peridynamics.loc_to_halo_fields(::$(esc(_storage_type)))
            return $(Expr(:tuple, _lth_field_names...))
        end
    end

    local _is_halo_fields = [
        quote
            function Peridynamics.is_halo_field(::$(esc(_storage_type)), ::Val{$(_field)})
                return true
            end
        end
        for _field in _halo_field_names
    ]

    local _storage_fields_expr = quote
        function Peridynamics.storage_fields_expr(::Base.Type{<:$(esc(_storage_type))})
            return $(QuoteNode(_decls))
        end
    end

    local _init_field_storages = [
        quote
            function Peridynamics.init_field_storage(::Base.Type{<:$(esc(_storage_type))},
                                                     system::Peridynamics.AbstractSystem,
                                                     ::Val{$(QuoteNode(_decl.name))},
                                                     extent::$(typeof(field_extent(_decl))))
                return $(init_field_storage_call(_decl))
            end
            function Peridynamics.init_field_storage(::Base.Type{<:$(esc(_storage_type))},
                                                     system::Peridynamics.AbstractSystem,
                                                     ::Val{$(QuoteNode(_decl.name))},
                                                     marker::Peridynamics.FullField)
                return $(alloc_solver_field_call(_decl))
            end
        end
        for _decl in _decls if !isnothing(_decl.shape)
    ]

    # the docstring is attached last, so that a `$(block_table(Name))` in it can already read
    # the declarations that were just registered
    local _doc = quote
        Base.@__doc__ $(esc(_storage_type))
    end

    local _checks = quote
        Peridynamics.typecheck_material($(esc(material)))
        Peridynamics.typecheck_storage($(esc(material)), $(esc(_storage_type)))
    end

    local _exprs = Expr(:block, _storage_struct, _dim_constructor, _get_n_dim,
                        _constructor, _storage_type_function,
                        _get_storage, _adapt_structure, _point_data_fields...,
                        _get_all_point_data_fields, _halo_to_loc_fields, _loc_to_halo_fields,
                        _is_halo_fields..., _storage_fields_expr, _init_field_storages...,
                        _constitutive_state, _damage_state, _doc, _checks)
    return _exprs
end

#=
`storage_type` returns the instantiation of the storage with the arrays of the CPU, which is
what a simulation that does not move its data anywhere else uses, and it takes the float type
of the simulation, which is the only parameter that is not fixed by the field declarations.
=#
function storage_type_function(material, storage_type, params, uses_sim_float,
                               cm_state_field=nothing, dmg_state_field=nothing)
    has_cm_state = !isnothing(cm_state_field)
    has_dmg_state = !isnothing(dmg_state_field)
    args = Any[esc(storage_type), DIM_TYPE_PARAM]
    uses_sim_float && push!(args, FLOAT_TYPE_PARAM)
    append!(args, storage_param_default(param) for param in params)
    # the nested states are the parameters that do not follow from the declarations,
    # because it is the constitutive model and the damage model of the material that
    # answer them; the order matches `storage_header_expr`
    has_cm_state && push!(args, :(Peridynamics.constitutive_storage_type(Peridynamics.get_constitutive_model(mat),
                                                                        $(FLOAT_TYPE_PARAM),
                                                                        Base.Val($(DIM_TYPE_PARAM)))))
    # the damage state is system-owned as well: which fields a model carries can depend
    # on the system family, e.g. the fracture bookkeeping of `CriticalStretch`, and the
    # dimension follows from the system type it is asked about
    has_dmg_state && push!(args, :(Peridynamics.damage_storage_type(Peridynamics.get_dmgmodel(mat),
                                                                    Peridynamics.system_type(mat,
                                                                                             $(FLOAT_TYPE_PARAM),
                                                                                             Base.Val($(DIM_TYPE_PARAM))),
                                                                    $(FLOAT_TYPE_PARAM))))
    instantiation = Expr(:curly, args...)
    return quote
        function Peridynamics.storage_type(mat::$(esc(material)),
