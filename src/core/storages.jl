"""
    @dmg_storage dmgmodel state
    @dmg_storage dmgmodel system state

$(extension_api_note())

Declare the state a damage model carries per bond or per point: the fracture bookkeeping it
maintains in [`calc_failure!`](@ref), and everything of its own, e.g. the accumulated
ductile damage of a Johnson-Cook model or the number of load cycles a bond has survived.
This is [`@cm_storage`](@ref) for a damage model instead of a constitutive model, and the
body accepts the same field declarations.

The generated state is reached inside [`calc_failure!`](@ref), [`calc_damage!`](@ref),
[`kinematic_weight`](@ref) and [`bond_integrity`](@ref) with [`damage_state`](@ref), and a
material carries it by declaring `dmg_state::DamageState`, see [`DamageState`](@ref). The
fields of the state are read flat off the storage, e.g. `storage.bond_active`, so kernels
never see the nesting.

A model that deletes bonds inherits the bookkeeping block of its system family, e.g.
`@inherit BondFracFields` for a bond system, and this is checked when a [`Job`](@ref) is
created. The optional `system` argument restricts a declaration to one system family, which
is how one model declares different states for different systems: [`CriticalStretch`](@ref)
declares [`BondFracFields`](@ref) for `AbstractBondSystem` and
[`InteractionFracFields`](@ref) for `InteractionSystem`. Without the argument the
declaration serves every system.

# Differences to `@storage`

- Every field has to be declared with a **field shape**. The initial value of a field the
    system knows better still comes from `init_field_system`, e.g. `n_active_bonds` starts
    as the neighbor count.
- The halo annotations [`@lth`](@ref) and [`@htl`](@ref) are **not allowed**. The state of a
    damage model is chunk-local, which is what bond state and point-local state are.
- A field with a point shape is point data of the storage that carries the state, so it can
    be exported to VTK files like a flat field, e.g. the `damage` of the fracture
    bookkeeping. A derived quantity is exported with an [`export_field`](@ref) method.

!!! note "A damage state does not make a model history dependent"
    Unlike [`@cm_storage`](@ref), this macro does **not** touch
    [`is_history_dependent`](@ref), so a stateful damage model stays compatible with every
    solver that supports fracture.

# Example

```julia
Peridynamics.@dmg_storage MyDamage struct MyDamageState
    @inherit BondFracFields
    bond_damage::BondScalar
end
```

See also [`@storage`](@ref), [`@cm_storage`](@ref), [`damage_state`](@ref),
[`damage_storage_type`](@ref), [`calc_failure!`](@ref).
"""
