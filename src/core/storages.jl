"""
    force_density_point!(storage, system, mat, params, t, Δt, i)

$(extension_api_note())

Calculate the internal force density of point `i` and accumulate it into
`storage.b_int`. This is the one method a material has to define; everything else about a
material is declared with `@params` and [`@storage`](@ref).

It is called once per local point and per time step, from inside a loop over
[`each_point_idx`](@ref) that runs on every thread and on every MPI rank. A method must
therefore only ever write to the columns of point `i`, and read every other point through
the system; then the same material runs under multithreading and MPI without a change.

# Arguments

- `storage`: The storage of the body chunk, holding every field of the simulation.
- `system`: The system of the body chunk, e.g. a [`BondSystem`](@ref). Dispatch on it to say
    which discretization the material is written for.
- `mat`: The material.
- `params`: The point parameters of point `i`. When a body has several parameter sets, the
    fallback resolves them with [`get_params`](@ref) before calling this method, so a method
    only ever sees one set.
- `t::Real`: The current simulation time.
- `Δt::Real`: The current time step.
- `i::Int`: The index of the local point that is evaluated.

# Example

A bond-based material, in full:

```julia
function Peridynamics.force_density_point!(storage, system::Peridynamics.BondSystem,
                                           mat::MyMaterial, params, t, Δt, i)
    for bond_id in Peridynamics.each_bond_idx(system, i)
        bond = system.bonds[bond_id]
        j, L = bond.neighbor, bond.length

        ΔXij = Peridynamics.get_vector_diff(system.position, i, j)
        Δxij = Peridynamics.get_vector_diff(storage.position, i, j)
        l = norm(Δxij)
        ε = (l - L) / L

        # the damage model decides whether the bond is still there
        stretch_based_failure!(storage, system, bond, params, ε, i, bond_id)

        b = storage.bond_active[bond_id] * params.bc * ε / l .* Δxij
        Peridynamics.update_add_vector!(storage.b_int, i, b .* system.volume[j])
    end
    return nothing
end
```

See also [`storage_type`](@ref), [`get_params`](@ref), [`each_bond_idx`](@ref).
"""
function force_density_point! end

